local function GetWeaponById(idNameOrHash)
    if not idNameOrHash then return end
    if type(idNameOrHash) == "string" then
        idNameOrHash = joaat(idNameOrHash)
    end
    return weapons[idNameOrHash]
end

local function GetWeaponsByCategory(category)
    if not category then return {} end
    category = category:upper()
    local ww = {}
    for id, weapon in pairs(weapons) do
        if weapon.Category == category then
            ww[#ww + 1] = weapon
        end
    end
    return ww
end

return {
    list = weapons,
    GetWeaponById = GetWeaponById,
    GetWeaponsByCategory = GetWeaponsByCategory,
}
